"use client";

import { useCallback, useEffect, useState } from 'react';
import { useTranslations } from 'next-intl';
import { CheckCircle2, FileDown, Loader2, QrCode } from 'lucide-react';
import { readImage, type PayableCode } from '../qr/types';

interface Claim {
    reference: string;
    status: 'PENDING' | 'POSTED' | 'REJECTED';
    source: string;
    amount: string;
    currency: string;
    paidAt: string;
    bankRef: string;
    note: string;
}
interface HowToPay { reference: string; currency: string; code: PayableCode | null; claims: Claim[] }

const headers = { 'X-Requested-With': 'XMLHttpRequest' };

/**
 * How to repay one loan, in the borrower portal (D-160): the lender's static
 * KHQR code, the loan reference to write in the payment remark, the printable
 * card, and "I have paid" — a claim the lender checks before it counts.
 */
export function PortalHowToPay({ loanId }: { loanId: string }) {
    const t = useTranslations('PortalPay');
    const [data, setData] = useState<HowToPay | null>(null);
    const [failed, setFailed] = useState(false);
    const [claiming, setClaiming] = useState(false);
    const load = useCallback(() => {
        fetch(`/api/proxy/borrower/loans/${loanId}`, { headers })
            .then((r) => (r.ok ? r.json() : Promise.reject(new Error(String(r.status)))))
            .then((l) => setData(l.howToPay as HowToPay))
            .catch(() => setFailed(true));
    }, [loanId]);
    useEffect(load, [load]);
    if (failed) return null;
    if (!data) return <p className="text-xs text-muted-foreground flex items-center gap-1 mt-3"><Loader2 size={12} className="animate-spin" /> {t('loading')}</p>;
    const c = data.code;
    return (
        <div className="mt-4 border-t border-border pt-4 space-y-3" data-testid="portal-how-to-pay">
            <h3 className="text-sm font-bold text-foreground flex items-center gap-2"><QrCode size={15} /> {t('title')}</h3>
            {!c ? <p className="text-sm text-muted-foreground">{t('noCode', { currency: data.currency })}</p> : (
                <div className="flex flex-col sm:flex-row gap-4 items-center sm:items-start">
                    {/* eslint-disable-next-line @next/next/no-img-element -- a data: URI generated by the API */}
                    <img src={c.image} alt={t('qrAlt')} className="w-44 h-44 rounded border border-border bg-white object-contain" />
                    <div className="text-sm space-y-2">
                        <div>
                            <p className="text-xs text-muted-foreground">{t('referenceLabel')}</p>
                            <p className="text-lg font-bold font-mono text-foreground" data-testid="portal-loan-reference">{data.reference}</p>
                        </div>
                        <p className="text-xs text-muted-foreground">{t('payTo', { name: c.merchantName, account: c.bakongAccountId, currency: c.currency })}</p>
                        <ol className="list-decimal ml-4 space-y-1 text-[13px] text-foreground">
                            <li>{t('step1')}</li>
                            <li>{t('step2', { currency: c.currency })}</li>
                            <li>{t('step3', { reference: data.reference })}</li>
                            <li>{t('step4')}</li>
                        </ol>
                        <p className="text-[11px] text-muted-foreground">{t('credited')}</p>
                        <p className="text-[11px] font-semibold text-red-700">{t('warning')}</p>
                        <div className="flex gap-3">
                            <a href={`/api/proxy/borrower/loans/${loanId}/how-to-pay?lang=km`} className="inline-flex items-center gap-1 text-xs font-medium text-primary hover:underline"><FileDown size={13} /> {t('cardKm')}</a>
                            <a href={`/api/proxy/borrower/loans/${loanId}/how-to-pay?lang=en`} className="inline-flex items-center gap-1 text-xs font-medium text-primary hover:underline"><FileDown size={13} /> {t('cardEn')}</a>
                        </div>
                    </div>
                </div>
            )}
            {c && !claiming && (
                <button type="button" onClick={() => setClaiming(true)} className="inline-flex items-center gap-1.5 px-3 py-1.5 text-sm font-semibold rounded bg-primary text-white hover:opacity-90">
                    <CheckCircle2 size={14} /> {t('iHavePaid')}
                </button>
            )}
            {claiming && <ClaimForm loanId={loanId} currency={data.currency} onDone={() => { setClaiming(false); load(); }} onCancel={() => setClaiming(false)} />}
            {data.claims.length > 0 && (
                <div className="space-y-1">
                    <p className="text-xs font-semibold text-muted-foreground">{t('yourPayments')}</p>
                    <ul className="text-[13px] divide-y divide-border border border-border rounded">
                        {data.claims.map((cl) => (
                            <li key={cl.reference} className="px-3 py-2 flex flex-wrap justify-between gap-2">
                                <span>{cl.currency} {cl.amount} · <span className="font-mono text-xs">{cl.bankRef}</span> · {new Date(cl.paidAt).toLocaleDateString()}</span>
                                <span className={cl.status === 'POSTED' ? 'text-emerald-700 font-semibold' : cl.status === 'REJECTED' ? 'text-red-700 font-semibold' : 'text-amber-700 font-semibold'}>
                                    {t(`status_${cl.status}`)}{cl.note ? ` — ${cl.note}` : ''}
                                </span>
                            </li>
                        ))}
                    </ul>
                </div>
            )}
        </div>
    );
}

function ClaimForm({ loanId, currency, onDone, onCancel }: { loanId: string; currency: string; onDone: () => void; onCancel: () => void }) {
    const t = useTranslations('PortalPay');
    const [amount, setAmount] = useState('');
    const [paidAt, setPaidAt] = useState('');
    const [bankRef, setBankRef] = useState('');
    const [file, setFile] = useState<File | null>(null);
    const [busy, setBusy] = useState(false);
    const [error, setError] = useState('');
    const input = 'w-full rounded border border-border px-2.5 py-1.5 text-sm bg-white';
    const submit = async () => {
        setError('');
        if (!/^\d+(\.\d{1,4})?$/.test(amount.trim()) || !/[1-9]/.test(amount)) return setError(t('errAmount'));
        if (!paidAt) return setError(t('errPaidAt'));
        if (bankRef.replace(/[^0-9a-z]/gi, '').length < 6) return setError(t('errBankRef'));
        setBusy(true);
        try {
            const shot = file ? await readImage(file) : null;
            const res = await fetch(`/api/proxy/lending/portal/loans/${loanId}/khqr-claims`, {
                method: 'POST',
                headers: { ...headers, 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    amount: amount.trim(), currency, paidAt: new Date(paidAt).toISOString(), bankRef: bankRef.trim(),
                    ...(shot ? { screenshot: { fileName: file!.name, mimeType: shot.mimeType, contentBase64: shot.base64 } } : {}),
                }),
            });
            if (!res.ok) {
                const body = await res.json().catch(() => ({}));
                setError(typeof body?.message === 'string' ? body.message : t('errGeneric'));
                return;
            }
            onDone();
        } finally {
            setBusy(false);
        }
    };
    return (
        <div className="border border-border rounded-md p-3 space-y-3 bg-slate-50" data-testid="portal-claim-form">
            <p className="text-xs text-muted-foreground">{t('claimIntro')}</p>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                <label className="text-xs font-medium text-foreground space-y-1"><span>{t('amount', { currency })}</span>
                    <input className={input} value={amount} onChange={(e) => setAmount(e.target.value)} inputMode="decimal" />
                </label>
                <label className="text-xs font-medium text-foreground space-y-1"><span>{t('paidAt')}</span>
                    <input className={input} type="datetime-local" value={paidAt} onChange={(e) => setPaidAt(e.target.value)} />
                </label>
                <label className="text-xs font-medium text-foreground space-y-1 sm:col-span-2"><span>{t('bankRef')}</span>
                    <input className={`${input} font-mono`} value={bankRef} onChange={(e) => setBankRef(e.target.value)} maxLength={120} />
                    <span className="block text-[11px] text-muted-foreground font-normal">{t('bankRefHint')}</span>
                </label>
                <label className="text-xs font-medium text-foreground space-y-1 sm:col-span-2"><span>{t('screenshot')}</span>
                    <input type="file" accept="image/png,image/jpeg,image/webp" onChange={(e) => setFile(e.target.files?.[0] ?? null)} className="block text-xs" />
                </label>
            </div>
            {error && <p className="text-xs text-red-700">{error}</p>}
            <div className="flex gap-2">
                <button type="button" onClick={submit} disabled={busy} className="px-3 py-1.5 text-sm font-semibold rounded bg-primary text-white disabled:opacity-60">{busy ? t('sending') : t('send')}</button>
                <button type="button" onClick={onCancel} className="px-3 py-1.5 text-sm rounded border border-border bg-white">{t('cancel')}</button>
            </div>
        </div>
    );
}
