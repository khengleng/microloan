"use client";

import { useState } from 'react';
import api from '@/lib/api';
import { useTranslations } from 'next-intl';
import { useToast } from '@/components/ui/toast';
import { useWorkspace } from '@/lib/workspace';
import { ActionPanel, Btn, Card, Empty, ErrorBox, Field, Notice, SelectInput, Spinner, TextInput } from '../ui';
import { clean, useAction, useApi } from '../useAsync';
import { StatusBadge } from '../StatusBadge';
import { Person } from '../People';
import { fmtDateTime } from '../format';
import { KHQR_CURRENCIES, readImage, type CodesView, type KhqrCode } from './types';

/**
 * The lender's static KHQR codes (D-160): one per currency for the lender,
 * optionally one per branch. Proposed by a holder of khqr.manage — generated
 * from the Bakong account details, or read from the image the bank gave —
 * and approved by a different person holding tenant_settings.approve.
 */
export function CodesPanel() {
    const t = useTranslations('LendingQr.codes');
    const { can } = useWorkspace();
    const view = useApi<CodesView>('/lending/khqr/codes');
    const [proposing, setProposing] = useState(false);
    const d = view.data;
    const branchName = (id: string | null) => (id ? d?.branches.find((b) => b.id === id)?.name ?? id : t('wholeLender'));
    return (
        <div className="space-y-4">
            {view.error && <ErrorBox error={view.error} />}
            {!d ? <Spinner /> : (
                <>
                    <Card
                        title={t('activeTitle')}
                        subtitle={t('activeSubtitle')}
                        actions={can('khqr.manage') && <Btn size="sm" variant="primary" onClick={() => setProposing(true)}>{t('propose')}</Btn>}
                    >
                        {proposing && (
                            <div className="mb-4">
                                <ProposeForm branches={d.branches} onClose={() => setProposing(false)} onDone={() => { setProposing(false); view.reload(); }} />
                            </div>
                        )}
                        {!d.active.length ? <Notice tone="warn" title={t('noneActive')}>{t('noneActiveBody')}</Notice> : (
                            <div className="grid gap-4 grid-cols-[repeat(auto-fill,minmax(260px,1fr))]">
                                {d.active.map((c) => <CodeTile key={c.id} c={c} scope={branchName(c.branchId)} />)}
                            </div>
                        )}
                    </Card>
                    <Card title={t('pendingTitle')} subtitle={t('pendingSubtitle')}>
                        {!d.pending.length ? <Empty>{t('nonePending')}</Empty> : (
                            <div className="grid gap-4 grid-cols-[repeat(auto-fill,minmax(260px,1fr))]">
                                {d.pending.map((c) => <CodeTile key={c.id} c={c} scope={branchName(c.branchId)} decide onDecided={view.reload} />)}
                            </div>
                        )}
                    </Card>
                    {d.history.length > 0 && (
                        <Card title={t('historyTitle')}>
                            <ul className="space-y-1 text-[12px] text-[#3C4257]">
                                {d.history.map((c) => (
                                    <li key={c.id}><StatusBadge status={c.status} /> {c.currency} · {branchName(c.branchId)} · <span className="font-mono">{c.bakongAccountId}</span> · {fmtDateTime(c.decidedAt)}</li>
                                ))}
                            </ul>
                        </Card>
                    )}
                </>
            )}
        </div>
    );
}

function CodeTile({ c, scope, decide, onDecided }: { c: KhqrCode; scope: string; decide?: boolean; onDecided?: () => void }) {
    const t = useTranslations('LendingQr.codes');
    const { showToast } = useToast();
    const { can, access } = useWorkspace();
    const { busy, error, run, clearError } = useAction();
    const mine = access?.principal.id === c.makerId;
    const allowed = can('tenant_settings.approve') && !mine;
    const decideAs = async (approve: boolean) => {
        const res = await run(approve ? 'approve' : 'reject', () => api.post(`/lending/khqr/codes/${c.id}/decision`, { approve }));
        if (res) { showToast(approve ? t('approved') : t('rejected'), 'success'); onDecided?.(); }
    };
    return (
        <div className="border border-[#E3E8EE] rounded-md p-3 space-y-2" data-testid={`khqr-code-${c.currency}`}>
            <div className="flex items-center justify-between">
                <span className="text-[13px] font-bold text-[#1A1F36]">{c.currency} · {scope}</span>
                <StatusBadge status={c.status} />
            </div>
            {/* eslint-disable-next-line @next/next/no-img-element -- a data: URI generated by the API */}
            {c.image && <img src={c.image} alt={t('qrAlt', { currency: c.currency })} className="w-40 h-40 mx-auto rounded border border-[#E3E8EE] bg-white" />}
            <div className="text-[12px] text-[#3C4257] space-y-0.5">
                <p><b>{c.merchantName}</b>, {c.merchantCity}</p>
                <p className="font-mono">{c.bakongAccountId}</p>
                {c.bankName && <p>{c.bankName}{c.accountNumber ? ` · ${c.accountNumber}` : ''}</p>}
                <p className="text-[#697386]">{t(`source_${c.source}`)}</p>
                <p className="text-[#697386]">{t('proposedBy')} <Person id={c.makerId} className="text-[12px]" />{c.checkerId && <> · {t('approvedBy')} <Person id={c.checkerId} className="text-[12px]" /></>}</p>
                {c.reason && <p className="text-[#697386] whitespace-pre-line">{c.reason}</p>}
            </div>
            {decide && (
                <div className="space-y-2">
                    <div className="flex gap-2">
                        <Btn size="sm" variant="primary" disabled={!allowed} reason={mine ? t('ownProposal') : !allowed ? t('needApprove') : undefined} busy={busy === 'approve'} onClick={() => decideAs(true)}>{t('approve')}</Btn>
                        <Btn size="sm" variant="ghost" disabled={!allowed} reason={mine ? t('ownProposal') : undefined} busy={busy === 'reject'} onClick={() => decideAs(false)}>{t('reject')}</Btn>
                    </div>
                    <ErrorBox error={error} onDismiss={clearError} />
                </div>
            )}
        </div>
    );
}

function ProposeForm({ branches, onDone, onClose }: { branches: CodesView['branches']; onDone: () => void; onClose: () => void }) {
    const t = useTranslations('LendingQr.codes');
    const { showToast } = useToast();
    const [mode, setMode] = useState<'GENERATE' | 'UPLOAD'>('GENERATE');
    const [currency, setCurrency] = useState('USD');
    const [branchId, setBranchId] = useState('');
    const [bakongAccountId, setAccount] = useState('');
    const [merchantName, setName] = useState('');
    const [merchantCity, setCity] = useState('');
    const [bankName, setBankName] = useState('');
    const [accountNumber, setAccountNumber] = useState('');
    const [reason, setReason] = useState('');
    const [image, setImage] = useState('');
    const [preview, setPreview] = useState<{ decoded: boolean; problem?: string; merchant?: { bakongAccountId: string; merchantName: string; merchantCity: string } } | null>(null);
    const { busy, error, run, clearError } = useAction();

    const pick = async (file?: File) => {
        if (!file) return;
        const img = await readImage(file);
        setImage(img.dataUrl);
        const res = await run('preview', () => api.post('/lending/khqr/codes/preview', { currency, image: img.dataUrl }));
        setPreview(res ? (res.data as typeof preview) : null);
    };
    const save = async () => {
        const body = clean({
            currency, branchId: branchId || undefined, mode, reason: reason.trim(),
            bakongAccountId: bakongAccountId.trim(), merchantName: merchantName.trim(), merchantCity: merchantCity.trim(),
            bankName: bankName.trim(), accountNumber: accountNumber.trim(), image: mode === 'UPLOAD' ? image : undefined,
        });
        const res = await run('save', () => api.post('/lending/khqr/codes', body));
        if (res) { showToast(t('proposed'), 'success'); onDone(); }
    };
    const needDetails = mode === 'GENERATE' || (preview !== null && !preview.decoded);
    return (
        <ActionPanel title={t('proposeTitle')} onClose={onClose}>
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                <Field label={t('how')}>
                    <SelectInput value={mode} onChange={(v) => { setMode(v as 'GENERATE' | 'UPLOAD'); setPreview(null); clearError(); }} options={[{ value: 'GENERATE', label: t('modeGenerate') }, { value: 'UPLOAD', label: t('modeUpload') }]} />
                </Field>
                <Field label={t('currency')}>
                    <SelectInput value={currency} onChange={setCurrency} options={KHQR_CURRENCIES} />
                </Field>
                <Field label={t('branch')} hint={t('branchHint')}>
                    <SelectInput value={branchId} onChange={setBranchId} placeholder={t('wholeLender')} options={branches.map((b) => ({ value: b.id, label: b.name }))} />
                </Field>
            </div>
            {mode === 'UPLOAD' && (
                <div className="space-y-2">
                    <Field label={t('image')} hint={t('imageHint')}>
                        <input type="file" accept="image/png,image/jpeg" aria-label={t('image')} onChange={(e) => pick(e.target.files?.[0])}
                            className="block text-[13px] text-[#3C4257] file:mr-3 file:rounded file:border file:border-[#E3E8EE] file:bg-white file:px-3 file:py-1 file:text-[12px] file:font-semibold" />
                    </Field>
                    {preview?.decoded && preview.merchant && (
                        <Notice tone="success" title={t('readOk')}>{t('readOkBody', { account: preview.merchant.bakongAccountId, name: preview.merchant.merchantName })}</Notice>
                    )}
                    {preview && !preview.decoded && <Notice tone="warn" title={t('readFailed')}>{t('readFailedBody', { problem: preview.problem ?? '' })}</Notice>}
                </div>
            )}
            {needDetails && (
                <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                    <Field label={t('bakongAccountId')} hint={t('bakongAccountIdHint')}><TextInput value={bakongAccountId} onChange={setAccount} maxLength={64} className="font-mono" /></Field>
                    <Field label={t('merchantName')} hint={t('merchantNameHint')}><TextInput value={merchantName} onChange={setName} maxLength={25} /></Field>
                    <Field label={t('merchantCity')}><TextInput value={merchantCity} onChange={setCity} maxLength={15} /></Field>
                </div>
            )}
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                <Field label={t('bankName')}><TextInput value={bankName} onChange={setBankName} maxLength={80} /></Field>
                <Field label={t('accountNumber')}><TextInput value={accountNumber} onChange={setAccountNumber} maxLength={40} /></Field>
                <Field label={t('reason')}><TextInput value={reason} onChange={setReason} maxLength={500} /></Field>
            </div>
            <p className="text-[11px] text-[#697386]">{t('makerChecker')}</p>
            <ErrorBox error={error} onDismiss={clearError} />
            <Btn variant="primary" onClick={save} busy={busy === 'save'} disabled={reason.trim().length < 3 || (mode === 'UPLOAD' && !image)}>{t('submit')}</Btn>
        </ActionPanel>
    );
}
