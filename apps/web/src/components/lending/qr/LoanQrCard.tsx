"use client";

import { useState } from 'react';
import { useTranslations } from 'next-intl';
import { useToast } from '@/components/ui/toast';
import { Btn, Card, Empty, ErrorBox, Notice, Spinner } from '../ui';
import { useApi } from '../useAsync';
import { ReceiptsTable } from './ReceiptsTable';
import { RecordReceiptForm } from './RecordReceiptForm';
import type { LoanReceiptsView } from './types';

type Can = (code: string) => { allowed: boolean; reason?: string };

/**
 * The loan's KHQR repayments (D-160): the static code its borrower pays,
 * the "How to pay" card to print, and the receipts recorded or claimed for
 * it, waiting for a second person or already posted.
 */
export function LoanQrCard({ loanId, active, can, onPosted }: {
    loanId: string; active: boolean; can: Can; onPosted: () => void;
}) {
    const t = useTranslations('LendingQr.loan');
    const { showToast } = useToast();
    const view = useApi<LoanReceiptsView>(`/lending/loans/${loanId}/khqr-receipts`);
    const [recording, setRecording] = useState(false);
    const record = can('payment.receipt.record');
    const d = view.data;
    return (
        <Card
            title={t('title')}
            subtitle={t('subtitle')}
            actions={
                <div className="flex flex-wrap gap-2">
                    <a href={`/api/proxy/lending/loans/${loanId}/how-to-pay?lang=en`} className="text-[12px] font-semibold text-[#635BFF] hover:underline" data-testid="how-to-pay-en">{t('cardEn')}</a>
                    <a href={`/api/proxy/lending/loans/${loanId}/how-to-pay?lang=km`} className="text-[12px] font-semibold text-[#635BFF] hover:underline" data-testid="how-to-pay-km">{t('cardKm')}</a>
                    {active && (
                        <Btn size="sm" onClick={() => setRecording(true)} disabled={!record.allowed} reason={record.reason}>
                            {t('record')}
                        </Btn>
                    )}
                </div>
            }
        >
            {view.error && <ErrorBox error={view.error} />}
            {!d ? <Spinner /> : (
                <div className="space-y-4">
                    {d.code ? (
                        <div className="flex flex-wrap items-center gap-4">
                            {/* eslint-disable-next-line @next/next/no-img-element -- a data: URI generated by the API */}
                            <img src={d.code.image} alt={t('qrAlt')} className="w-28 h-28 rounded border border-[#E3E8EE] bg-white" />
                            <div className="text-[13px] text-[#3C4257] space-y-0.5">
                                <p><b>{d.code.merchantName}</b> · {d.code.currency}</p>
                                <p className="font-mono text-[12px]">{d.code.bakongAccountId}</p>
                                <p>{t('remarkRule', { reference: d.reference })}</p>
                            </div>
                        </div>
                    ) : (
                        <Notice tone="warn" title={t('noCode')}>{t('noCodeBody', { currency: d.currency })}</Notice>
                    )}
                    {recording && (
                        <RecordReceiptForm
                            loanId={loanId}
                            currency={d.currency}
                            onClose={() => setRecording(false)}
                            onDone={() => { showToast(t('recorded'), 'success'); setRecording(false); view.reload(); }}
                        />
                    )}
                    {d.receipts.length === 0 ? <Empty>{t('none')}</Empty> : (
                        <ReceiptsTable receipts={d.receipts} showLoan={false} onChanged={() => { view.reload(); onPosted(); }} />
                    )}
                </div>
            )}
        </Card>
    );
}
